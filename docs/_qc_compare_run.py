"""One-shot QC: our ocr.py vs pytesseract vs EasyOCR on resources fixtures."""
from __future__ import annotations

import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESOURCES = ROOT / "resources"
FIXTURES = [
    "zayavlenie_otpusk.png",
    "spravka_s_mesta_raboty.png",
    "nakladnaya_tovarnaya.png",
]
OUT = ROOT / "docs" / "qc-copypastepad-log.md"
VENV_PY = ROOT / ".venv" / "Scripts" / "python.exe"
PY = str(VENV_PY if VENV_PY.exists() else Path(sys.executable))


def clip(text: str, limit: int = 500) -> str:
    text = (text or "").strip()
    if len(text) <= limit:
        return text
    return text[: limit - 3] + "..."


def run_ours(image: Path, dest: Path) -> str:
    code = subprocess.call(
        [
            PY,
            str(ROOT / "ocr.py"),
            str(image),
            "-o",
            str(dest),
            "--lang",
            "ru+en",
            "--no-preprocess",
            "--ui",
            "en",
        ],
        cwd=str(ROOT),
    )
    if code != 0 or not dest.exists():
        return f"(ours failed, exit {code})"
    return dest.read_text(encoding="utf-8")


def run_tesseract(image: Path) -> str:
    dest = Path(tempfile.gettempdir()) / f"qc_{image.name}.tess.txt"
    code = subprocess.call(
        [
            PY,
            str(ROOT / "ocr.py"),
            str(image),
            "-o",
            str(dest),
            "--lang",
            "ru+en",
            "--engine",
            "tesseract",
            "--no-preprocess",
            "--ui",
            "en",
        ],
        cwd=str(ROOT),
    )
    if code != 0:
        try:
            import pytesseract
            from PIL import Image

            return clip(
                pytesseract.image_to_string(Image.open(image), lang="rus+eng")
                or f"(ocr.py tesseract exit {code})"
            )
        except Exception as error:  # noqa: BLE001
            return f"(tesseract unavailable: {error}; ocr.py exit {code})"
    return dest.read_text(encoding="utf-8") if dest.exists() else f"(no output, exit {code})"


def run_easyocr(image: Path) -> str:
    try:
        import easyocr
        from PIL import Image
        import numpy as np
    except ImportError:
        return "(easyocr not installed)"
    try:
        models = ROOT / "models"
        reader = easyocr.Reader(
            ["ru", "en"],
            gpu=False,
            verbose=False,
            model_storage_directory=str(models),
            download_enabled=False,
        )
        rgb = np.array(Image.open(image).convert("RGB"))
        rows = reader.readtext(rgb, detail=0, paragraph=False)
        return "\n".join(str(item) for item in rows)
    except Exception as error:  # noqa: BLE001
        return f"(easyocr error: {error})"


def main() -> int:
    lines = [
        "# QC log: fixtures vs ours / Tesseract / EasyOCR",
        "",
        "Generated by `docs/_qc_compare_run.py`.",
        "",
    ]
    with tempfile.TemporaryDirectory() as temp_dir:
        temp = Path(temp_dir)
        for name in FIXTURES:
            image = RESOURCES / name
            lines.append(f"## {name}")
            lines.append("")
            if not image.exists():
                lines.append("(missing fixture)")
                lines.append("")
                continue
            ours = run_ours(image, temp / f"{name}.ours.txt")
            tess = run_tesseract(image)
            easy = run_easyocr(image)
            lines.append("### Ours")
            lines.append("```")
            lines.append(clip(ours))
            lines.append("```")
            lines.append("")
            lines.append("### CPP-like Tesseract")
            lines.append("```")
            lines.append(clip(tess))
            lines.append("```")
            lines.append("")
            lines.append("### CPP-like EasyOCR")
            lines.append("```")
            lines.append(clip(easy))
            lines.append("```")
            lines.append("")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
